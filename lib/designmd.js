/**
 * Exports a habitat design folder as a DESIGN.md file in Google's open format.
 *
 * Google Labs' DESIGN.md (github.com/google-labs-code/design.md, version
 * "alpha") is a single file: YAML front matter with colours, typography,
 * spacing, corner radii and component styling, then Markdown sections in a
 * fixed order (Overview, Colors, Typography, Layout, Elevation & Depth,
 * Shapes, Components, Do's and Don'ts). Stitch writes it, and a growing
 * number of tools and collections read it.
 *
 * habitat holds more than that format has room for: why each rule exists,
 * who said so, the research behind it, and how journeys flow. This export
 * keeps what fits. The facts go in the front matter, and the judgement goes
 * in the prose: token meanings under Colors, each component's purpose and
 * when to use each variant under Components, and every never-because rule
 * under Do's and Don'ts. Principles, interaction rules and journeys follow
 * as extra sections, which the format allows.
 *
 * The habitat folder stays the source. The file says it was generated, so
 * re-running the export replaces it and nobody edits the copy by mistake.
 */

import YAML from "yaml";

export const GENERATED = "<!-- Generated by habitat";

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/[._\s]+/g, "-").toLowerCase();

// Which DESIGN.md group a habitat token belongs to, and its name there.
const GROUPS = [
  ["colors", /^(color|colour|colors)\./],
  ["spacing", /^(space|spacing)\./],
  ["rounded", /^(radius|rounded|border-radius|borderRadius)\./],
];
const TYPOGRAPHY_FIELDS = ["fontFamily", "fontSize", "fontWeight", "lineHeight", "letterSpacing", "fontFeature", "fontVariation"];
const isTypography = (t) => t.type === "typography" || (t.value && typeof t.value === "object" && "fontFamily" in t.value);

function placeToken(t) {
  if (isTypography(t)) return ["typography", kebab(t.name.replace(/^(type|typography|font|text)\.(style\.)?/, ""))];
  for (const [group, prefix] of GROUPS) {
    if (prefix.test(t.name)) return [group, kebab(t.name.replace(prefix, ""))];
  }
  return null;
}

// A component binding key, like "primary.background.hover", becomes a
// DESIGN.md component ("button-primary-hover") and property ("backgroundColor").
const PROPERTIES = [
  [/^(background|bg|fill|surface)$/i, "backgroundColor"],
  [/^(text|foreground|fg|color)$/i, "textColor"],
  [/^(radius|rounded|corner|cornerRadius)$/i, "rounded"],
  [/^padding/i, "padding"],
  [/^(typography|textStyle|type)$/i, "typography"],
  [/^(height|minHeight)$/i, "height"],
  [/^(width|minWidth)$/i, "width"],
  [/^size$/i, "size"],
];
function componentProperty(key) {
  const parts = key.split(".");
  for (let i = 0; i < parts.length; i++) {
    for (const [pattern, property] of PROPERTIES) {
      if (!pattern.test(parts[i])) continue;
      // "paddingMd" carries its variant in the same word.
      const suffix = property === "padding" ? parts[i].replace(/^padding/i, "") : "";
      const variant = [...parts.slice(0, i), ...(suffix ? [suffix] : []), ...parts.slice(i + 1)].map(kebab);
      return { property, variant };
    }
  }
  return null;
}

// Split the habitat DESIGN.md into its "## " sections, by lower-case heading.
function sections(body = "") {
  const out = new Map();
  let current = null;
  for (const line of body.replace(/<!--[\s\S]*?-->/g, "").split("\n")) {
    const h = line.match(/^##\s+(.+?)\s*$/);
    if (h) {
      current = h[1].toLowerCase();
      out.set(current, []);
    } else if (current) out.get(current).push(line);
  }
  return new Map([...out].map(([k, v]) => [k, v.join("\n").trim()]));
}
const find = (map, ...names) => {
  for (const [k, v] of map) if (names.some((n) => k.startsWith(n)) && v) return v;
  return "";
};
const clean = (s) => String(s ?? "").replace(/\s+/g, " ").trim();

export function toDesignMd(design, { name, primary } = {}) {
  const tokens = design.tokens?.data?.tokens || [];
  const byName = new Map(tokens.map((t) => [t.name, t]));
  const resolve = (t, seen = new Set()) => {
    if (!t?.aliasOf || seen.has(t.name)) return t?.value;
    seen.add(t.name);
    return resolve(byName.get(t.aliasOf), seen);
  };

  // Tokens: semantic and component tiers only. Habitat components bind to
  // roles, so the raw palette has nothing to say in a DESIGN.md.
  const front = { version: "alpha" };
  const groups = { colors: {}, typography: {}, rounded: {}, spacing: {} };
  const placed = new Map(); // habitat token name -> "{group.key}"
  for (const t of tokens) {
    if (t.tier === "primitive" || t.replacedBy) continue;
    const where = placeToken(t);
    const value = resolve(t);
    if (!where || value === undefined) continue;
    const [group, key] = where;
    if (group === "typography") {
      if (typeof value !== "object") continue;
      groups.typography[key] = Object.fromEntries(TYPOGRAPHY_FIELDS.filter((f) => value[f] !== undefined).map((f) => [f, value[f]]));
    } else {
      if (typeof value !== "string" && typeof value !== "number") continue;
      groups[group][key] = value;
    }
    placed.set(t.name, `{${group}.${key}}`);
  }
  // The format expects a "primary" colour. Use the one named, or the brand colour.
  const primaryToken = primary ?? ["color.primary", "color.brand.default", "color.brand.primary", "color.brand"].find((n) => byName.has(n));
  if (primaryToken && groups.colors.primary === undefined) {
    const value = resolve(byName.get(primaryToken));
    if (typeof value === "string") groups.colors = { primary: value, ...groups.colors };
  }

  // Components: each habitat binding that maps to a DESIGN.md property.
  const components = {};
  for (const c of design.components) {
    if (c.data?.status === "deprecated") continue;
    const base = kebab(c.data?.name?.canonical || "");
    for (const [key, binding] of Object.entries(c.data?.tokens || {})) {
      const prop = componentProperty(key);
      if (!prop) continue;
      const refs = String(binding).split(/\s+/).filter(Boolean);
      // One token becomes a reference; several (like padding "space.md space.lg") become their values.
      let value;
      if (refs.length === 1 && placed.has(refs[0])) value = placed.get(refs[0]);
      else {
        const values = refs.map((r) => resolve(byName.get(r)));
        if (values.some((v) => typeof v !== "string" && typeof v !== "number")) continue;
        value = values.join(" ");
      }
      const id = [base, ...prop.variant].join("-");
      components[id] = { ...components[id], [prop.property]: value };
    }
  }

  const principles = sections(design.principles?.body);
  const product = find(principles, "the product", "product");
  front.name = name || "Design system";
  if (product) front.description = clean(product.split(/(?<=\.)\s/)[0]);
  for (const [group, values] of Object.entries(groups)) if (Object.keys(values).length) front[group] = values;
  if (Object.keys(components).length) front.components = components;

  // The prose: judgement, in the format's section order.
  const body = [`${GENERATED} from ${design.root.split("/").pop()}/. Edit those files, then run \`habitat export\` again. -->`, ""];
  const section = (title, ...parts) => {
    const text = parts.filter(Boolean).join("\n\n").trim();
    if (text) body.push(`## ${title}`, "", text, "");
  };
  const tokenList = (group) =>
    tokens
      .filter((t) => placed.get(t.name)?.startsWith(`{${group}.`))
      .map((t) => {
        const key = placed.get(t.name).slice(group.length + 2, -1);
        const extra = [t.useFor && `Use for: ${clean(t.useFor)}`, t.avoid && `Avoid: ${clean(t.avoid)}`].filter(Boolean).join(" ");
        return `- **${key}:** ${clean(t.meaning)}${extra ? ` ${extra}` : ""}`;
      })
      .join("\n");

  section("Overview", product, find(principles, "language", "voice"));
  section("Colors", find(principles, "colour", "color"), tokenList("colors"));
  section("Typography", tokenList("typography"));
  section("Layout", find(principles, "layout"), tokenList("spacing"));
  section("Shapes", tokenList("rounded"));

  const componentProse = design.components
    .filter((c) => c.data?.status !== "deprecated")
    .map(({ data }) => {
      const lines = [`### ${data.name.canonical}`, "", clean(data.purpose), ""];
      for (const v of data.variants || []) if (v.whenToUse) lines.push(`- **${v.name}:** ${clean(v.whenToUse)}`);
      return lines.join("\n");
    })
    .join("\n\n");
  section("Components", find(principles, "choosing between"), componentProse);

  // "Place two primary buttons in the same view." -> "Don't place two primary buttons in the same view (Button)."
  const dont = (a, where) =>
    `- **Don't** ${clean(a.never).replace(/\.$/, "").replace(/^\w/, (c) => c.toLowerCase())} (${where}). ${clean(a.because)}`;
  const rules = [
    ...design.components.flatMap(({ data }) => (data?.antiPatterns || []).map((a) => dont(a, data.name.canonical))),
    ...(design.flows || []).flatMap(({ data }) => (data?.antiPatterns || []).map((a) => dont(a, data.name))),
  ];
  section("Do's and Don'ts", find(principles, "never"), rules.join("\n"));

  // What the format has no section for, kept as extra sections it preserves.
  section("Principles", find(principles, "principles"));
  section("Interaction rules", find(principles, "interaction"));
  section("Core journeys", find(principles, "core journeys", "journeys"));

  const yaml = YAML.stringify(front, { lineWidth: 0, defaultStringType: "QUOTE_DOUBLE", defaultKeyType: "PLAIN" });
  return `---\n${yaml}---\n\n${body.join("\n").trim()}\n`;
}
